// Pulls captions for the curated example videos and writes them to
// src/lib/curated-transcripts.ts, which the example pages render as a
// transcript. Prefers an uploaded caption track over YouTube's auto captions.
//
//   node --import tsx scripts/youtube/export-transcripts.ts
//   ... --force   re-download transcripts that already exist
//
// Each download costs 200 API units (about 50 videos a day on the default quota).
import { writeFileSync } from "node:fs";
import { join } from "node:path";

import { CURATED_VIDEOS } from "../../src/lib/curated-videos";
import { CURATED_TRANSCRIPTS } from "../../src/lib/curated-transcripts";
import { vttToText } from "../../src/lib/transcripts";
import { flag, isQuotaError, youtubeClient } from "./client";

const OUTPUT = join(process.cwd(), "src/lib/curated-transcripts.ts");

const youtube = youtubeClient();
const force = flag("force") === true;

async function transcriptFor(videoId: string): Promise<string | undefined> {
  const tracks = await youtube.captions.list({
    part: ["snippet"],
    videoId,
  });
  const items = tracks.data.items ?? [];
  const english = (lang?: string | null) => lang?.startsWith("en") ?? false;
  const track =
    items.find(
      (t) => t.snippet?.trackKind !== "asr" && english(t.snippet?.language),
    ) ??
    items.find((t) => t.snippet?.trackKind !== "asr") ??
    items.find((t) => english(t.snippet?.language)) ??
    items[0];
  if (!track?.id) return undefined;

  const vtt = await youtube.captions.download(
    { id: track.id, tfmt: "vtt" },
    { responseType: "text" },
  );
  return vttToText(String(vtt.data));
}

async function main() {
  const transcripts: Record<string, string> = { ...CURATED_TRANSCRIPTS };

  for (const video of CURATED_VIDEOS) {
    if (transcripts[video.videoId] && !force) continue;
    try {
      const text = await transcriptFor(video.videoId);
      if (text) {
        transcripts[video.videoId] = text;
        console.log(`ok    ${video.videoId}  ${video.title}`);
      } else {
        console.log(`none  ${video.videoId}  ${video.title} (no captions yet)`);
      }
    } catch (error) {
      if (isQuotaError(error)) {
        console.log("Daily API quota used up. Saving what we have.");
        break;
      }
      console.warn(`fail  ${video.videoId}  ${(error as Error).message}`);
    }
  }

  writeFileSync(
    OUTPUT,
    `// Generated by scripts/youtube/export-transcripts.ts. Do not edit by hand.
// Maps a YouTube video id to the plain-text narration shown on its example page.
export const CURATED_TRANSCRIPTS: Record<string, string> = ${JSON.stringify(
      transcripts,
      null,
      2,
    )};
`,
  );
  console.log(
    `Wrote ${Object.keys(transcripts).length} transcripts to ${OUTPUT}`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
